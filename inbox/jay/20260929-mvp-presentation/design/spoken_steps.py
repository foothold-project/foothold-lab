CLICK = '(클릭)'


def apply(slides):
    """단계 장의 spoken 을 바꾸고, (클릭) 수가 단계 수와 같은지 검사한다."""
    stepped = {s['title']: s['steps'] for s in slides if s.get('steps')}
    own = {s['title'] for s in slides if s.get('steps') and s['title'] not in SPOKEN_STEPS and s['spoken'].count(CLICK) == s['steps']}
    missing = sorted(set(stepped) - set(SPOKEN_STEPS) - own)   # 멘트를 스스로 가진 장(axes_scene)은 통과
    assert not missing, '단계 장인데 단계별 멘트가 없다: %s' % missing
    for s in slides:
        t = s['title']
        if t not in SPOKEN_STEPS:
            continue
        text = SPOKEN_STEPS[t]
        n = text.count(CLICK)
        assert n == s['steps'], '%s: (클릭) %d개 != 단계 %d' % (t, n, s['steps'])
        s['spoken'] = text
    return len([t for t in SPOKEN_STEPS if t in stepped])
