# Select near-threshold cells for the 500-episode expansion (Q: "임계값 부근 ... 500 episodes 로 확대").
# Rule (declared before looking at expansion results): a family x cell is expanded if, for EITHER
# checkpoint, the Wilson 95% interval of the cell-rule pass rate contains 0.90 or the Wilson 95%
# interval of survival contains 0.95. Only Q-as-written runs (main and off-platform) are considered;
# the heading-hold variant is not expanded. Writes out/expand_plan.json and run_expand.sh.

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
FAMS = ["flat", "wave", "slope_up", "slope_down", "rough_slope", "stairs_up", "stairs_down", "obstacles"]
ITS = ["20000", "20499"]


def cells_of(tag):
    p = os.path.join(OUT, tag, "cells.json")
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def near(s):
    lo, hi = s["pass_ci"]
    slo, shi = s["survival_ci"]
    return (lo <= 0.90 <= hi) or (slo <= 0.95 <= shi)


plan = {"main": {}, "offplat": {}}
for fam in FAMS:
    sel = set()
    for it in ITS:
        c = cells_of(f"m{it}_{fam}")
        for s in c or []:
            if near(s):
                sel.add(s["cell"])
    if sel:
        plan["main"][fam] = sorted(sel)
for it in ITS:
    c = cells_of(f"m{it}_offplat")
    for s in c or []:
        if near(s):
            plan["offplat"].setdefault(s["family"], set()).add(s["cell"])
plan["offplat"] = {k: sorted(v) for k, v in plan["offplat"].items()}
n_ep = 500 * (sum(len(v) for v in plan["main"].values()) + sum(len(v) for v in plan["offplat"].values())) * len(ITS)
plan["episodes_total"] = n_ep
with open(os.path.join(OUT, "expand_plan.json"), "w", encoding="utf-8") as f:
    json.dump(plan, f, indent=1)
print(json.dumps(plan, indent=1))

lines = [
    "#!/usr/bin/env bash",
    "# Q-E1 500-episode expansion, generated by q_expand_plan.py from out/expand_plan.json.",
    "# Same GPU 1 settings. One process per (checkpoint, family, mode); N = cells x 500.",
    "set -u",
    'cd "$(dirname "$0")"',
    "PY=C:/Users/AI-WS01/anaconda3/envs/isaac311-moects/python.exe",
    "RUN=C:/isaac/ext/go2_rl_robotlab/logs/rsl_rl/go2_moe_cts/2026-10-10_12-47-48_e1_seed42_n8192",
    "export CUDA_DEVICE_ORDER=PCI_BUS_ID CUDA_VISIBLE_DEVICES=1 OMNI_KIT_ACCEPT_EULA=YES PYTHONUNBUFFERED=1",
    "one() {",
    "  local tag=$1; shift",
    '  if [ -f "out/$tag/cells.json" ]; then echo "RUN $tag SKIP"; return; fi',
    "  local t0=$(date +%s)",
    '  "$PY" q_eval.py --headless --tag "$tag" "$@" > "out/$tag.log" 2>&1',
    '  echo "RUN $tag EXIT $? $(( $(date +%s) - t0 ))s $(nvidia-smi --query-gpu=index,memory.used --format=csv,noheader | tr \'\\n\' \' \')"',
    "}",
]
for it in ITS:
    for fam, cells in plan["main"].items():
        lines.append(f'one x500_m{it}_{fam} --policy student --checkpoint "$RUN/model_{it}.pt" --families {fam} '
                     f'--cells {",".join(cells)} --episodes 500')
    for fam, cells in plan["offplat"].items():
        lines.append(f'one x500_m{it}_offplat_{fam} --policy student --checkpoint "$RUN/model_{it}.pt" --families {fam} '
                     f'--cells {",".join(cells)} --episodes 500 --spawn_offset stand=2.5,yaw=2.5,stop=1.75')
lines.append('echo "EXPAND DONE"')
with open(os.path.join(HERE, "run_expand.sh"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("runs:", sum(1 for x in lines if x.startswith("one ")))
