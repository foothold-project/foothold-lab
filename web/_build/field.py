def fail(fid, sym, cause, found, fix, left=None, cost=None):
    """실패 카드: 증상 → 원인 → 어떻게 알아냈나 → 해결"""
    c = ('<span class="fx-cost">%s</span>' % cost) if cost else ''
    l = ('<div class="fx-left"><span class="fx-lk">남은 문제</span>%s</div>' % left) if left else ''
    return f'''<div class="fx" id="fx-{fid}">
  <div class="fx-top"><span class="fx-id">{fid}</span><span class="fx-sym">{sym}</span>{c}</div>
  <div class="fx-body">
    <div class="fx-r"><span class="fx-k">원인</span><span class="fx-v">{cause}</span></div>
    <div class="fx-r"><span class="fx-k">어떻게 알아냈나</span><span class="fx-v">{found}</span></div>
    <div class="fx-r fx-fix"><span class="fx-k">해결</span><span class="fx-v">{fix}</span></div>
  </div>{l}
</div>'''


def nums(title, rows, note=None):
    """실측 숫자 표"""
    body = ''.join('<tr><td>%s</td><td class="nv">%s</td><td class="nn">%s</td></tr>' % r for r in rows)
    n = ('<div class="nt-note">%s</div>' % note) if note else ''
    return f'''<div class="nt">
  <div class="nt-h">{title}</div>
  <table class="nt-t"><thead><tr><th>항목</th><th>값</th><th>비고</th></tr></thead><tbody>{body}</tbody></table>
  {n}</div>'''


def block(intro, *parts):
    """실전 기록 묶음"""
    return ('\n<div class="fld">\n'
            '<div class="fld-h"><span class="fld-t">실전 기록</span>'
            '<span class="fld-s">선행 사례에서 실제로 일어난 일 · '
            '<a href="https://iamjaehka13.blog/categories/unitree-go2/" target="_blank" rel="noopener">'
            '출처 ↗</a></span></div>\n'
            f'<p class="fld-i">{intro}</p>\n' + ''.join(parts) + '</div>\n')


