def selftest():
    """규칙이 실제로 작동하는지 확인한다. 하나라도 못 잡으면 검사 자체를 신뢰할 수 없다.

    ★ 두 방향을 모두 본다. 잡아야 할 것을 잡는가(미탐), 잡으면 안 될 것을 놔두는가(과탐).
      과탐을 방치하면 사람이 ALLOW 로 다 밀어넣고, 그 순간 이 문은 없는 것과 같아진다.
    """
    rules = {k: v for k, v in BLOCK} | {k: v for k, v in WARN}
    dead = []
    for label, sample in SELFTEST:
        pat = rules.get(label)
        if not pat or not re.search(pat, sample):
            dead.append((label, sample, '못 잡음'))
    for label, sample in SELFTEST_NEGATIVE:
        pat = rules.get(label)
        if pat and re.search(pat, mask_geometry(sample)):
            dead.append((label, sample, '과탐: 잡으면 안 되는데 잡음'))
    return dead

