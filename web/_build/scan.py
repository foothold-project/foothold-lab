#   주민등록번호 패턴으로 잡혔다(2026-08-11). 값 하나를 ALLOW 로 미는 대신 규칙을 고친다. 
#   비밀은 d/points/viewBox/transform 안에 살지 않는다.
GEOMETRY_ATTR = re.compile(r'\s(?:d|points|viewBox|transform)="[^"]*"')


def mask_geometry(text):
    """기하 속성 값을 공백으로 덮는다. 줄바꿈은 보존해 줄 번호가 어긋나지 않게."""
    return GEOMETRY_ATTR.sub(lambda m: re.sub(r'[^\n]', ' ', m.group(0)), text)


