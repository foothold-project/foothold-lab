def redact(html):
    """웹으로 나갈 문자열에서 민감한 값을 자리표시자로 바꾼다. (원문은 안 건드린다)"""
    hits = []
    for pat, repl, why in REDACT:
        html, n = re.subn(pat, repl, html)
        if n:
            hits.append((why, n))
    # 가려진 값에 붙어 있던 복사 버튼은 없앤다. 자리표시자를 복사해 봐야 쓸모가 없고,
    # "복사했는데 안 되네" 라는 혼란만 만든다.
    html = re.sub(r'<button class="copy"[^>]*data-copy="[^"]*&lt;[^"]*"[^>]*>.*?</button>',
                  '', html, flags=re.S)
    return html, hits


def _lines(text, m):
    return text[:m.start()].count('\n') + 1


def scan_text(name, text):
    """한 파일을 훑는다. (치명, 경고) 목록을 돌려준다."""
    # ★ 2026-08-28. 전에는 «잡힌 문자열 전체»가 ALLOW 값과 똑같아야 통과였다.
    #   금액 규칙을 문맥 기반으로 바꾸자(「예산 ... 55,484,000원」) 잡히는 문자열에
    #   앞뒤 말과 HTML 태그가 섞여 들어와 ALLOW 가 한 건도 안 맞았다.
    #   허용의 뜻은 «이 값을 안다»이지 «이 문장을 안다»가 아니다. 부분 일치로 본다.
    allowed = [(r, v) for r, v, _, _ in ALLOW]
    text = mask_geometry(text)
    fatal, warn = [], []
    for label, pat in BLOCK:
        for m in re.finditer(pat, text):
            fatal.append((name, _lines(text, m), label, m.group(0)[:60]))
    for label, pat in WARN:
        for m in re.finditer(pat, text):
            got = m.group(0)
            if any(r == label and v in got for r, v in allowed):
                continue
            warn.append((name, _lines(text, m), label, got[:60]))
    return fatal, warn


def scan(site_dir, exts=('.html', '.json', '.md', '.js', '.css', '.txt')):
    fatal, warn, n = [], [], 0
    for root, dirs, files in os.walk(site_dir):
        dirs[:] = [d for d in dirs if d not in ('.git', 'node_modules')]
        for f in sorted(files):
            if not f.endswith(exts):
                continue
            p = os.path.join(root, f)
            rel = os.path.relpath(p, site_dir)
            try:
                t = io.open(p, encoding='utf-8', errors='replace').read()
            except Exception as e:
                warn.append((rel, 0, '읽기 실패', str(e))); continue
            a, b = scan_text(rel, t)
            fatal += a; warn += b; n += 1
    return fatal, warn, n


