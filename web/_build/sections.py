CSS = r"""
/* 신설 절 표식: 원본이 아니라 우리가 얹은 절임을 드러낸다 */
.slide .sid:has(+ h2)::after{content:''}
"""


def insert(html):
    """기준 절 바로 뒤에 새 절을 끼운다."""
    placed = []
    for s in SECTIONS:
        pat = re.compile(r'(<section class="slide"[^>]*data-id="%s">.*?</section>)'
                         % re.escape(s['after']), re.S)
        m = pat.search(html)
        if not m:
            print('  [!] 기준 절 없음: %s (뒤에 %s 를 넣으려 했음)' % (s['after'], s['sid']))
            continue
        html = html[:m.end(1)] + s['html'] + html[m.end(1):]
        placed.append('%s→%s' % (s['after'], s['sid']))
    print('신설 절    : %s' % (', '.join(placed) or '없음'))
    return html
