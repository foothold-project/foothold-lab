def main() -> int:
    from collections import defaultdict
    per = defaultdict(list)
    for path, old, new, why in EDITS:
        per[path].append((old, new, why))

    failed = []
    for path, items in per.items():
        t = io.open(path, encoding="utf-8").read()
        for old, new, why in items:
            if old not in t:
                failed.append((path, why, old.split("\n")[0][:64]))
                continue
            t = t.replace(old, new, 1)
            print("  고쳤다 · %s" % why)
        if "—" in t:
            print("  ** em dash 가 들어갔다 · %s **" % path)
            return 1
        io.open(path, "w", encoding="utf-8").write(t)

    if failed:
        print()
        print("  ** 못 찾은 것 %d 건 **" % len(failed))
        for path, why, head in failed:
            print("    %s · %s" % (path.split("/")[-1], why))
            print("      %s" % head)
        return 1
    print()
    print("  반영 %d 건" % len(EDITS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
